router = APIRouter(prefix="/api/incidents", tags=["Incidents"])

@router.get("", response_model=Dict[str, Any])
async def list_incidents(
    zone: Optional[str] = None,
    priority: Optional[str] = None,
    status_filter: Optional[str] = None,
    recommendation: Optional[str] = None,
    search: Optional[str] = None,
    limit: int = Query(50, ge=1, le=100),
    offset: int = Query(0, ge=0),
    current_user: dict = Depends(get_current_user),
):
    """Retrieve list of candidate incidents with filtering and pagination."""
    with db_session() as conn:
        cursor = conn.cursor()
        query = "SELECT * FROM incidents WHERE 1=1"
        params: List[Any] = []

        if zone:
            query += " AND fictional_zone = ?"
            params.append(zone)
        if priority:
            query += " AND priority = ?"
            params.append(priority)
        if status_filter:
            query += " AND status = ?"
            params.append(status_filter)
        if recommendation:
            query += " AND recommendation = ?"
            params.append(recommendation)
        if search:
            query += " AND (incident_id LIKE ? OR title LIKE ?)"
            term = f"%{search}%"
            params.extend([term, term])

        count_query = query.replace("SELECT *", "SELECT COUNT(*)", 1)
        cursor.execute(count_query, params)
        total = cursor.fetchone()[0]

        query += " ORDER BY updated_at DESC LIMIT ? OFFSET ?;"
        params.extend([limit, offset])
        cursor.execute(query, params)
        rows = cursor.fetchall()

        results = []
        for r in rows:
            d = dict_from_row(r)
            d["score_components"] = json.loads(d.get("score_components") or "{}")
            d["conflicting_evidence"] = json.loads(d.get("conflicting_evidence") or "[]")
            d["missing_evidence"] = json.loads(d.get("missing_evidence") or "[]")
            d["source_health_summary"] = json.loads(d.get("source_health_summary") or "{}")
            results.append(d)

        return {
            "total": total,
            "limit": limit,
            "offset": offset,
            "incidents": results,
            "notice": "Candidate incident groupings generated by transparent heuristic rules.",
        }

@router.get("/{incident_id}", response_model=IncidentResponse)
async def get_incident_detail(incident_id: str, current_user: dict = Depends(get_current_user)):
    """Retrieve detailed incident view, supporting timeline, and correlation justification."""
    with db_session() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM incidents WHERE incident_id = ?;", (incident_id,))
        inc_row = cursor.fetchone()
        if not inc_row:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Incident {incident_id} not found.")

        incident_dict = dict_from_row(inc_row)
        incident_dict["score_components"] = json.loads(incident_dict.get("score_components") or "{}")
        incident_dict["conflicting_evidence"] = json.loads(incident_dict.get("conflicting_evidence") or "[]")
        incident_dict["missing_evidence"] = json.loads(incident_dict.get("missing_evidence") or "[]")
        incident_dict["source_health_summary"] = json.loads(incident_dict.get("source_health_summary") or "{}")

        # Fetch linked reports ordered chronologically
        cursor.execute("""
        SELECT r.report_id, r.source_id, r.source_type, r.fictional_zone,
               r.event_type, r.description, r.confidence_score, r.report_timestamp,
               r.data_quality_status, ir.correlation_rule, ir.match_strength, ir.is_duplicate
        FROM incident_reports ir
        JOIN reports r ON ir.report_id = r.report_id
        WHERE ir.incident_id = ?
        ORDER BY r.report_timestamp ASC;
        """, (incident_id,))
        report_links = []
        for row in cursor.fetchall():
            rd = dict_from_row(row)
            rd["is_duplicate"] = bool(rd.get("is_duplicate", 0))
            report_links.append(IncidentReportLink(**rd))

        incident_dict["related_reports"] = report_links
        return IncidentResponse(**incident_dict)

@router.post("/run-correlation")
async def trigger_correlation_run(
    current_user: dict = Depends(require_role(["Administrator", "Analyst"])),
    request: Request = None,
):
    """Executes a correlation analysis cycle across all available reports."""
    client_ip = request.client.host if (request and request.client) else "127.0.0.1"
    with db_session() as conn:
        result = run_correlation_cycle(conn)
        record_audit_event(
            conn, actor_username=current_user["username"], actor_role=current_user["role"],
            action="CORRELATION_ANALYSIS_EXECUTED", target_type="SYSTEM", target_id="CORRELATION_ENGINE",
            details=f"Analyzed {result['reports_analyzed']} reports, formed {result['incidents_created']} incidents",
            actor_id=current_user["id"], ip_address=client_ip
        )
        return result

@router.post("/{incident_id}/separate-report")
async def separate_report_from_incident(
    incident_id: str,
    report_id: str,
    reason: str,
    current_user: dict = Depends(require_role(["Administrator", "Analyst", "Reviewer"])),
    request: Request = None,
):
    """Allows an authorized reviewer or analyst to detach an incorrectly grouped report."""
    if not reason.strip():
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="A mandatory reason is required to separate a report.")

    client_ip = request.client.host if (request and request.client) else "127.0.0.1"
    with db_session() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT incident_id FROM incident_reports WHERE incident_id = ? AND report_id = ?;", (incident_id, report_id))
        if not cursor.fetchone():
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Report {report_id} is not linked to incident {incident_id}.")

        cursor.execute("DELETE FROM incident_reports WHERE incident_id = ? AND report_id = ?;", (incident_id, report_id))
        cursor.execute("UPDATE reports SET status = 'INGESTED' WHERE report_id = ?;", (report_id,))

        record_audit_event(
            conn, actor_username=current_user["username"], actor_role=current_user["role"],
            action="REPORT_SEPARATED_FROM_INCIDENT", target_type="INCIDENT", target_id=incident_id,
            previous_state=f"Report {report_id} linked", resulting_state=f"Report {report_id} unlinked",
            details=f"Reason: {reason}", actor_id=current_user["id"], ip_address=client_ip
        )

        return {"message": f"Report {report_id} detached from incident {incident_id} successfully."}
